function showlist() {
	$(".ld-ext-right-list").addClass('running');
    $(".ld-ext-right-list").prop('disabled', true);
	$.ajax({
		url: site_url + '/awards/wab_list',
		type: 'post',
		data: {
			band: $("#band").val(),
            mode: $("#mode").val(),
            qsl:  $("#qsl").is(":checked"),
            lotw: $("#lotw").is(":checked"),
            eqsl: $("#eqsl").is(":checked"),
            qrz: $("#qrz").is(":checked"),
            sat: $("#sats").val(),
            orbit: $("#orbits").val(),
		},
		success: function (data) {
			wablist(data);
		},
		error: function (data) {
		},
	})
}

