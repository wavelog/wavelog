 let confirmedColor = user_map_custom.qsoconfirm.color;
let workedColor = user_map_custom.qso.color;

$('#band').change(function(){
	var band = $("#band option:selected").text();
	if (band != "SAT") {
		$("#sats").val('All');
		$("#orbits").val('All');
		$("#sats").hide();
		$("#orbits").hide();
		$("#satslabel").hide();
		$("#orbitslabel").hide();
	} else {
		$("#sats").show();
		$("#orbits").show();
		$("#orbitslabel").show();
		$("#satslabel").show();
	}
});

